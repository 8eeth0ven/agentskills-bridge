"""Mermaid workflow emitter:AgentIR -> workflow.md(GitHub 渲染即流程图视图)。

链路:AgentIR ──WorkflowIR.from_agent_ir──▶ WorkflowIR ──渲染──▶ markdown。

产物:
    <out>/workflow.md    frontmatter(name/description)+ `# 标题` + 一段简介
                         + ```mermaid flowchart TD 块(节点 `id["名称"]`、边
                         `a --> |label| b`、首节点 classDef start 高亮)
                         + 每节点一节 `## Step N: name`(放该步 prompt)
                         + 知识文件清单
    <out>/knowledge/*.md 知识文档按 filename 拷贝
    <out>/README.md      GitHub 渲染说明 + 人工执行指引
"""

from __future__ import annotations

from pathlib import Path
from typing import List, Optional

try:
    from converter.ir import AgentIR
    from converter.wir import WorkflowIR
except ImportError:  # pragma: no cover - 包内相对导入兜底
    from ..ir import AgentIR  # type: ignore
    from ..wir import WorkflowIR  # type: ignore

__all__ = ["emit_mermaid_workflow"]


def emit_mermaid_workflow(ir: AgentIR, out_dir: str | Path) -> Path:
    """把 AgentIR 写成 mermaid workflow 目录,返回 out_dir。"""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    w = WorkflowIR.from_agent_ir(ir)
    _write_knowledge(w, out)
    (out / "workflow.md").write_text(_workflow_md(w), encoding="utf-8")
    (out / "README.md").write_text(_readme(w), encoding="utf-8")
    return out


# ---------- mermaid 渲染 ----------

def _esc_label(text: str) -> str:
    """mermaid `id["label"]` 引号标签转义:双引号 → #quot;。"""
    return (text or "").replace("\\", "\\\\").replace('"', "#quot;")


def _frontmatter_value(text: str) -> str:
    """frontmatter 单行化,避免多行值破坏平面解析。"""
    return " ".join((text or "").split())


def _mermaid_block(w: WorkflowIR) -> str:
    lines = ["flowchart TD"]
    for node in w.nodes:
        lines.append(f'    {node.id}["{_esc_label(node.name)}"]')
    for edge in w.edges:
        if edge.label:
            lines.append(f"    {edge.source} --> |{_esc_label(edge.label)}| {edge.target}")
        else:
            lines.append(f"    {edge.source} --> {edge.target}")
    if w.nodes:
        lines.append("    classDef start fill:#e1f5fe,stroke:#0288d1,stroke-width:2px")
        lines.append(f"    class {w.nodes[0].id} start")
    return "\n".join(lines)


def _workflow_md(w: WorkflowIR) -> str:
    title = w.display_name or w.name
    intro = (w.description or "").strip() or (
        f"{title} workflow with {len(w.nodes)} step(s), generated by agentskills-bridge."
    )
    parts: List[str] = []
    parts.append("---")
    parts.append(f"name: {w.name}")
    parts.append(f"description: {_frontmatter_value(w.description) or title}")
    parts.append("---")
    parts.append("")
    parts.append(f"# {title}")
    parts.append("")
    parts.append(_frontmatter_value(intro))
    parts.append("")
    parts.append("```mermaid")
    parts.append(_mermaid_block(w))
    parts.append("```")
    parts.append("")
    for i, node in enumerate(w.nodes, 1):
        parts.append(f"## Step {i}: {node.name}")
        parts.append("")
        parts.append((node.prompt or "").strip())
        parts.append("")
    # Source Context:原文全文回源节 —— 步骤节点只是工作流骨架,skill 正文的
    # Overview 等非步骤章节在此保全,roundtrip 不丢内容(评测 F_prompt 曾因
    # 缺此节降至 0.71);parse_mermaid_workflow 优先读本节为 system_prompt。
    if (w.system_prompt or "").strip():
        parts.append("## Source Context")
        parts.append("")
        parts.append(w.system_prompt.strip())
        parts.append("")
    parts.append("## Knowledge Files")
    parts.append("")
    docs = [d for d in w.knowledge if _safe_filename(d.filename)]
    if docs:
        parts.extend(
            f"- knowledge/{_safe_filename(d.filename)} —— {d.title or d.filename}"
            for d in docs
        )
    else:
        parts.append("- (本 workflow 未附带知识文档)")
    parts.append("")
    return "\n".join(parts)


# ---------- 知识文档拷贝(与 langflow emitter 同策略) ----------

def _safe_filename(filename: str) -> Optional[str]:
    """过滤非法路径名:为空、. / ..、含 / 或 \\ 或 .. 的一律拒绝。"""
    name = (filename or "").strip()
    if not name or name in (".", ".."):
        return None
    if "/" in name or "\\" in name or ".." in name:
        return None
    return name


def _write_knowledge(w: WorkflowIR, out: Path) -> List[str]:
    written: List[str] = []
    for doc in w.knowledge:
        name = _safe_filename(doc.filename)
        if name is None:
            continue
        kdir = out / "knowledge"
        kdir.mkdir(parents=True, exist_ok=True)
        (kdir / name).write_text(doc.content or "", encoding="utf-8")
        written.append(name)
    return written


# ---------- README ----------

def _readme(w: WorkflowIR) -> str:
    title = w.display_name or w.name
    steps = "\n".join(f"{i}. {n.name}" for i, n in enumerate(w.nodes, 1)) or "- (无步骤)"
    docs = [d for d in w.knowledge if _safe_filename(d.filename)]
    listing = "\n".join(
        f"- knowledge/{_safe_filename(d.filename)} —— {d.title or d.filename}" for d in docs
    ) or "- (本 workflow 未附带知识文档)"
    return f"""# {title} —— Mermaid Workflow(由 agentskills-bridge 生成)

## 文件

- workflow.md —— 主文件:frontmatter + 流程图 + 分步指令 + 知识清单
- knowledge/ —— 参考知识文档:
{listing}
- README.md —— 本说明

## 查看方式(GitHub 渲染即视图)

把整个目录推到 GitHub(或任何支持 mermaid 的 markdown 渲染器),打开
workflow.md 即可直接看到渲染好的 flowchart 流程图,无需任何工具;
本地 VS Code 装「Markdown Preview Mermaid Support」扩展同样可预览。

## 人工执行指引

workflow.md 是「给人/给 agent 照着跑」的执行单:

1. 按流程图顺序逐步执行,首节点(start 高亮)是入口;
2. 每步的完整指令在正文 `## Step N: <步骤名>` 小节,照 prompt 执行,
   有 `Expected output:` 行时以它为该步的完成标准;
{steps}
3. 需要背景资料时查阅 knowledge/ 下对应文档;
4. 全部步骤完成即 workflow 结束,末步产物即最终输出。
"""
